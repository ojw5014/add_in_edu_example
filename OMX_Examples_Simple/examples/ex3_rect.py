print("- 변 1/4 완료")
c3d.PlayXyzPath(1800, 0, 0, [250, 35, 63.5], 0, 90, 0, 14, [11, 12, 13])    # 변 2
print("- 변 2/4 완료")
c3d.PlayXyzPath(1800, 0, 0, [170, 35, 63.5], 0, 90, 0, 14, [11, 12, 13])    # 변 3
print("- 변 3/4 완료")
c3d.PlayXyzPath(1800, 0, 0, [170, -35, 63.5], 0, 90, 0, 14, [11, 12, 13])   # 변 4
print("- 변 4/4 완료")

c3d.PlayXyz(800, 0, 0, 170, -35, 100, 0, 90, 0, 14, 11, 12, 13)      # 펜 들기
