# -*- coding: utf-8 -*-
# ============================================================
# 심플 예제 1: 픽앤플레이스 — 한 줄에 한 명령, 로봇 제어 명령만 사용
#
# 모든 명령은 오픈지그웨어(OpenJigWare.dll) 함수를 그대로 쓴다:
#   c3d.Play(시간ms, 딜레이ms, ID,각도, ID,각도, ...)   ← 관절 이동 후 딜레이ms 만큼 대기
#   c3d.PlayXyz(시간ms, 딜레이ms, 수식, x, y, z, Rx, Ry, Rz, 손목ID, 위치관절들)
#     Ry=90 이면 툴(그리퍼)이 수직 아래를 향한다
#   Ojw.CTimer.Wait(ms)                                  ← 단순 대기
#
# 잡기/놓기는 실물 로봇과 같은 개념이다 — 별도 명령이 없다.
#   그리퍼를 닫으면 근처(40mm 이내) 제품이 잡히고, 열면 그 자리에 놓인다.
# 장면(제품 위치)은 Run 을 누를 때마다 자동으로 초기화된다.
# scene 은 실물 로봇 통신 전용이다: open/close/torqon/torqoff/syncread
# ============================================================
import clr, os, sys
if "__file__" in dir():                              # 단독 실행(VS Code 등) — 상위 폴더의 DLL 경로 추가
    sys.path.append(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
clr.AddReference("OpenJigWare")                      # 오픈지그웨어 라이브러리
from OpenJigWare import Ojw

try:
    scene                                            # 실행기(3D 창) 안 — scene 이 준비되어 있다
except NameError:
    scene = Ojw.CScene_t.CreateOmx()                 # 단독 실행 — 3D 창 없이 동일 동작(실물 가능)

c3d = scene.c3d

# [실물 로봇] 아래 세 줄 맨 앞의 # 한 글자만 지우면 같은 코드로 실물 OMX 도 함께 움직인다
#scene.open(4, 1000000)       # 통신 열기 — U2D2 포트(COM4), 통신 속도 1Mbps
#scene.torqon()               # 토크 ON — 켜기 전 실물 자세를 읽어 3D 를 먼저 정렬(점프 없음)
#scene.syncread()             # 실물 관절각을 읽어 로그로 확인

# ── PlayXyz 인자 읽는 법 ─────────────────────────────────────────────
# c3d.PlayXyz(시간ms, 딜레이ms, 수식번호, x, y, z, Rx, Ry, Rz, 손목모터ID, 위치관절ID 3개)
#   · 시간ms/딜레이ms   : 이동에 걸리는 시간 / 도착 후 잠깐 멈추는 시간
#   · 수식번호(0)       : 로봇 기구학 수식 번호 (이 로봇은 0 하나)
#   · x, y, z          : 로봇팔 끝(TCP = 그리퍼 중심)이 갈 좌표 (mm)
#   · Rx, Ry, Rz       : 툴(그리퍼) 자세 각도(도) — Ry=90 이면 수직 아래를 향한다
#   · 손목모터ID (14)   : 툴 자세(피치)를 만드는 손목 모터의 ID
#   · 위치관절 (11,12,13): TCP 위치를 만드는 관절 3개 — 각도는 역기구학이 계산
# c3d.Play(시간ms, 딜레이ms, ID,각도, ID,각도, ...) : 모터 ID 에 각도(도)를 직접 지정

print("픽앤플레이스 시작")
c3d.Play(1200, 0, 11, 0, 12, -25, 13, 35, 14, 35, 15, 0)             # 홈 자세
c3d.Play(400, 0, 16, 30)                                             # 그리퍼 활짝
c3d.PlayXyz(1200, 0, 0, 200, 110, 100, 0, 90, 0, 14, 11, 12, 13)     # 제품 위 경유점
c3d.PlayXyz(1000, 0, 0, 200, 110, 45, 0, 90, 0, 14, 11, 12, 13)      # 내려가기
c3d.Play(400, 200, 16, 4)                                            # 닫아서 잡기 (제품 굵기만큼)
c3d.PlayXyz(1000, 0, 0, 200, 110, 100, 0, 90, 0, 14, 11, 12, 13)     # 들어올리기
c3d.PlayXyz(1400, 0, 0, 210, -110, 100, 0, 90, 0, 14, 11, 12, 13)    # 목표 위로 이동
c3d.PlayXyz(1000, 0, 0, 210, -110, 55, 0, 90, 0, 14, 11, 12, 13)     # 내려놓을 높이
c3d.Play(400, 0, 16, 30)                                             # 열어서 놓기
Ojw.CTimer.Wait(300)                                                 # 잠시 대기
c3d.PlayXyz(800, 0, 0, 210, -110, 100, 0, 90, 0, 14, 11, 12, 13)     # 복귀 경유점
c3d.Play(1200, 0, 11, 0, 12, -25, 13, 35, 14, 35, 15, 0)             # 홈 복귀
print("완료!")

# [실물 로봇] 끝나면 아래 두 줄 맨 앞의 # 한 글자만 지워 토크를 끄고 통신을 닫는다
