pts += [176.5, -32.1, Z]
pts += [181.5, -34.3, Z]
pts += [188.0, -35.0, Z]        # 코너 4 라운드 끝 = 시작점 (닫힌 도형)

c3d.PlayXyz(1200, 0, 0, 188, -35, 100, 0, 90, 0, 14, 11, 12, 13)     # 시작점 위
c3d.PlayXyz(800, 0, 0, 188, -35, 63.5, 0, 90, 0, 14, 11, 12, 13)     # 펜 내리기
c3d.PlayXyzPath(7000, 0, 0, pts, 0, 90, 0, 14, [11, 12, 13])         # 전체를 한 획으로
print("- 베지어 사각형 완료")

