# 경로 점 나열 — 시작점 (188, -35) 에서 시계 반대로 한 바퀴 (Z = 펜이 판에 닿는 높이)
Z = 63.5
pts = []
pts += [232.0, -35.0, Z]        # 변 1 직선 끝
pts += [238.5, -34.3, Z]        # 코너 1 라운드...
pts += [243.5, -32.1, Z]
pts += [247.1, -28.5, Z]
pts += [249.3, -23.5, Z]
pts += [250.0, -17.0, Z]        # 코너 1 라운드 끝
pts += [250.0, 17.0, Z]         # 변 2 직선 끝
pts += [249.3, 23.5, Z]         # 코너 2 라운드...
pts += [247.1, 28.5, Z]
pts += [243.5, 32.1, Z]
pts += [238.5, 34.3, Z]
pts += [232.0, 35.0, Z]         # 코너 2 라운드 끝
pts += [188.0, 35.0, Z]         # 변 3 직선 끝
pts += [181.5, 34.3, Z]         # 코너 3 라운드...
pts += [176.5, 32.1, Z]
pts += [172.9, 28.5, Z]
pts += [170.7, 23.5, Z]
pts += [170.0, 17.0, Z]         # 코너 3 라운드 끝
pts += [170.0, -17.0, Z]        # 변 4 직선 끝
pts += [170.7, -23.5, Z]        # 코너 4 라운드...
